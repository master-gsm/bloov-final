/*
  # إضافة صلاحية للمدراء لرؤية جميع المستخدمين
  
  1. التغييرات
    - إضافة policy جديد يسمح للمدراء برؤية جميع المستخدمين
    - يستخدم دالة get_my_role() للتحقق من أن المستخدم مدير
  
  2. الأمان
    - فقط المستخدمون الذين لديهم دور "admin" يمكنهم رؤية جميع المستخدمين
    - المستخدمون العاديون يمكنهم فقط رؤية ملفاتهم الشخصية (من خلال policy موجود مسبقاً)
*/

-- إضافة policy للمدراء لرؤية جميع المستخدمين
CREATE POLICY "Admins can view all users"
  ON users FOR SELECT
  TO authenticated
  USING (get_my_role() = 'admin');